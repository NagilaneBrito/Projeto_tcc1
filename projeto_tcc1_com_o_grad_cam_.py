class YOLO26GradCAM:
    """Grad-CAM++ para YOLO26 — reaproveita um único forward."""

    def __init__(self, detector, target_layer, classe_alvo):
        self.detector = detector
        self.target_layer = target_layer
        self.classe_alvo = int(classe_alvo)
        self.activations = None
        self.gradients = None
        self._handles = []

    def registrar_hooks(self):
        self._handles.append(
            self.target_layer.register_forward_hook(self._fwd_hook))
        self._handles.append(
            self.target_layer.register_full_backward_hook(self._bwd_hook))
        return self

    def remover_hooks(self):
        for h in self._handles:
            h.remove()
        self._handles.clear()

    def _fwd_hook(self, m, i, o):
        self.activations = o

    def _bwd_hook(self, m, gi, go):
        if go is not None and len(go) > 0:
            self.gradients = go[0]

    @staticmethod
    def extrair_preds(raw):
        if isinstance(raw, dict):
            return raw.get("one2many", raw)
        if isinstance(raw, tuple):
            for el in raw:
                if isinstance(el, dict):
                    if "one2many" in el:
                        return el["one2many"]
                    if "scores" in el:
                        return el
        raise RuntimeError("one2many não encontrado no raw_output.")

    def gerar(self, raw_output, indice_candidato):
        preds = self.extrair_preds(raw_output)
        if "scores" not in preds:
            raise RuntimeError("Saída interna sem 'scores'.")

        scores = preds["scores"]
        score = scores[0, self.classe_alvo, indice_candidato]

        # Backward direto no logit (evita saturação do sigmoid)
        self.detector.zero_grad(set_to_none=True)
        score.backward(retain_graph=False)

        if self.activations is None:
            raise RuntimeError("Sem ativações.")
        if self.gradients is None:
            raise RuntimeError("Sem gradientes.")

        A = self.activations
        G = self.gradients

        # ---------- Grad-CAM++ ----------
        G2 = G ** 2
        G3 = G ** 3
        denom = 2.0 * G2 + (A * G3)
        denom = torch.where(denom != 0, denom, torch.ones_like(denom))
        alpha = G2 / (denom + 1e-8)

        pesos = (alpha * torch.relu(G)).sum(dim=(2, 3), keepdim=True)
        cam = (pesos * A).sum(dim=1)
        cam = torch.relu(cam)[0].detach().cpu().numpy()

        mn, mx = cam.min(), cam.max()
        if mx - mn > 1e-12:
            cam = (cam - mn) / (mx - mn)
        else:
            cam = np.zeros_like(cam)
        return cam


def caixa_original_para_letterbox(caixa, w, h, tam=640):
    x1, y1, x2, y2 = caixa
    e = min(tam / w, tam / h)
    nw, nh = w * e, h * e
    px, py = (tam - nw) / 2, (tam - nh) / 2
    return np.array(
        [x1*e+px, y1*e+py, x2*e+px, y2*e+py], dtype=np.float32
    )


def xywh_para_xyxy(c):
    if not isinstance(c, torch.Tensor):
        c = torch.as_tensor(c)
    x, y, w, h = c[:, 0], c[:, 1], c[:, 2], c[:, 3]
    return torch.stack([x-w/2, y-h/2, x+w/2, y+h/2], dim=1)


def calcular_iou(alvo, caixas):
    x1 = np.maximum(alvo[0], caixas[:, 0])
    y1 = np.maximum(alvo[1], caixas[:, 1])
    x2 = np.minimum(alvo[2], caixas[:, 2])
    y2 = np.minimum(alvo[3], caixas[:, 3])
    inter = np.maximum(0, x2-x1) * np.maximum(0, y2-y1)
    aa = max(0, alvo[2]-alvo[0]) * max(0, alvo[3]-alvo[1])
    ac = np.maximum(0, caixas[:, 2]-caixas[:, 0]) * np.maximum(0, caixas[:, 3]-caixas[:, 1])
    u = aa + ac - inter
    iou = np.zeros_like(inter)
    m = u > 0
    iou[m] = inter[m] / u[m]
    return iou


def encontrar_candidato(preds, head, caixa, classe):
    # Tenta método público primeiro, depois o privado
    if hasattr(head, "get_decode_boxes"):
        caixas = head.get_decode_boxes(preds)[0]
    else:
        caixas = head._get_decode_boxes(preds)[0]
    if caixas.dim() == 2 and caixas.shape[0] == 4:
        caixas = caixas.transpose(0, 1)
    caixas_np = xywh_para_xyxy(caixas).detach().cpu().numpy()
    ious = calcular_iou(caixa, caixas_np)
    idx = int(np.argmax(ious))
    return idx, float(ious[idx])


def preparar_imagem(img_bgr):
    img = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
    lb = LetterBox(new_shape=(IMAGE_SIZE, IMAGE_SIZE), auto=False, stride=32)
    img_lb = lb(image=img)
    f = img_lb.astype(np.float32) / 255.0
    t = torch.from_numpy(f).permute(2, 0, 1).unsqueeze(0)

    device_real = next(detector.parameters()).device
    t = t.to(device_real)
    t.requires_grad_(True)
    return img_lb, t


def gerar_gradcam_imagem(imagem, resultado):
    """Gera Grad-CAM++ reaproveitando UM único forward por detecção."""
    img_orig = imagem.copy()
    h0, w0 = img_orig.shape[:2]

    if resultado.boxes is None or len(resultado.boxes) == 0:
        return img_orig

    confs = resultado.boxes.conf.detach().cpu().numpy()
    ordem = np.argsort(-confs)[:GRADCAM_MAX_DETECCOES]

    _, input_tensor = preparar_imagem(img_orig)
    vis = img_orig.copy()

    for n, ib in enumerate(ordem, start=1):
        classe = int(resultado.boxes.cls[ib].item())
        conf = float(resultado.boxes.conf[ib].item())
        caixa_orig = resultado.boxes.xyxy[ib].detach().cpu().numpy()
        nome_cls = CLASS_NAMES.get(classe, f"classe_{classe}")

        print(f"  Detecção {n}: {nome_cls} | conf={conf:.3f}")

        caixa_lb = caixa_original_para_letterbox(caixa_orig, w0, h0)

        gc = YOLO26GradCAM(detector, target_layer, classe)
        gc.registrar_hooks()

        estado = getattr(head, "end2end", None)
        if estado is not None:
            head.end2end = False

        try:
            detector.zero_grad(set_to_none=True)
            with torch.enable_grad():
                raw = detector(input_tensor)

            preds = gc.extrair_preds(raw)
            idx_cand, iou = encontrar_candidato(preds, head, caixa_lb, classe)
            print(f"    candidato={idx_cand} | IoU={iou:.3f}")

            gradcam = gc.gerar(raw, idx_cand)

        except Exception as e:
            print(f"    [ERRO] {e}")
            import traceback
            traceback.print_exc()
            continue
        finally:
            if estado is not None:
                head.end2end = estado
            gc.remover_hooks()

        # ---------- CAM → tamanho original ----------
        cam640 = cv2.resize(gradcam, (IMAGE_SIZE, IMAGE_SIZE),
                            interpolation=cv2.INTER_CUBIC)
        cam640 = cv2.GaussianBlur(cam640, (11, 11), 0)

        e = min(IMAGE_SIZE / w0, IMAGE_SIZE / h0)
        nw, nh = int(round(w0 * e)), int(round(h0 * e))
        px = int(round((IMAGE_SIZE - nw) / 2))
        py = int(round((IMAGE_SIZE - nh) / 2))
        cam_sp = cam640[py:py+nh, px:px+nw]
        cam_o = cv2.resize(cam_sp, (w0, h0), interpolation=cv2.INTER_CUBIC)
        cam_o = np.clip(cam_o, 0, 1)

        # ---------- MÁSCARA PELA CAIXA (foco na pessoa) ----------
        mascara = np.zeros((h0, w0), dtype=np.uint8)
        x1m, y1m, x2m, y2m = caixa_orig.astype(int)
        x1m = max(0, min(w0-1, x1m)); y1m = max(0, min(h0-1, y1m))
        x2m = max(0, min(w0-1, x2m)); y2m = max(0, min(h0-1, y2m))

        mw = int((x2m - x1m) * 0.2)
        mh = int((y2m - y1m) * 0.2)
        mx1 = max(0, x1m - mw)
        my1 = max(0, y1m - mh)
        mx2 = min(w0, x2m + mw)
        my2 = min(h0, y2m + mh)
        mascara[my1:my2, mx1:mx2] = 255

        mascara = cv2.GaussianBlur(mascara, (31, 31), 0).astype(np.float32) / 255.0
        cam_o = cam_o * mascara

        mn, mx = cam_o.min(), cam_o.max()
        if mx - mn > 1e-12:
            cam_o = (cam_o - mn) / (mx - mn)

        # ---------- Colormap + overlay ----------
        hm = cv2.applyColorMap(np.uint8(cam_o * 255), cv2.COLORMAP_JET)
        vis = cv2.addWeighted(vis, 0.55, hm, 0.45, 0)

        # ---------- Caixa verde + label ----------
        x1, y1, x2, y2 = caixa_orig.astype(int)
        x1 = max(0, min(w0-1, x1)); y1 = max(0, min(h0-1, y1))
        x2 = max(0, min(w0-1, x2)); y2 = max(0, min(h0-1, y2))
        cv2.rectangle(vis, (x1, y1), (x2, y2), (0, 255, 0), 3)
        cv2.putText(
            vis, f"{nome_cls} {conf:.2f}",
            (x1+5, max(23, y1-10)),
            cv2.FONT_HERSHEY_SIMPLEX, 0.65,
            (255, 255, 255), 2,
        )

    return vis


