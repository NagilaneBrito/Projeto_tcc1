"""Funções utilitárias para analisar labels"""

def listar_images(images_path):
    if not os.path.exists(images_path):
        return []
    return sorted([
        arq for arq in os.listdir(images_path)
        if arq.split(".")[-1] in IMAGE_EXTENSIONS
    ])


def ler_label(label_path):
    """Lê uma label no formato YOLO (classe x y w h)."""
    anotacoes = []
    if not os.path.exists(label_path):
        return anotacoes
    with open(label_path, "r") as f:
        for num_linha, linha in enumerate(f.readlines(), start=1):
            linha = linha.strip()
            if not linha:
                continue
            partes = linha.split()
            if len(partes) != 5:
                print(f"[!] Label inválida: {label_path} | linha {num_linha}")
                continue
            try:
                anotacoes.append({
                    "classe": int(float(partes[0])),
                    "x": float(partes[1]),
                    "y": float(partes[2]),
                    "largura": float(partes[3]),
                    "altura": float(partes[4]),
                })
            except ValueError:
                print(f"[!] Valores inválidos: {label_path} | linha {num_linha}")
    return anotacoes


def analisar_dataset(split):
    print("\n" + "=" * 70)
    print(f" ANALISANDO: {split.upper()}")
    print("=" * 70)

    images_path = f"{DATASET_PATH}/{split}/images"
    labels_path = f"{DATASET_PATH}/{split}/labels"

    imagens = listar_images(images_path)
    contagem_classes = Counter()
    total_anotacoes = 0

    for img in imagens:
        nome_base = os.path.splitext(img)[0]
        label_path = os.path.join(labels_path, nome_base + ".txt")
        anotacoes = ler_label(label_path)
        for a in anotacoes:
            contagem_classes[a["classe"]] += 1
            total_anotacoes += 1

    print(f" Imagens: {len(imagens)}")
    print(f" Anotações: {total_anotacoes}")
    print(f" não-violência (0): {contagem_classes[0]}")
    print(f" violência (1):     {contagem_classes[1]}")

    return {
        "imagens": len(imagens),
        "anotacoes": total_anotacoes,
        "violencia": contagem_classes[VIOLENCE_CLASS_ID],
        "nao_violencia": contagem_classes[NON_VIOLENCE_CLASS_ID],
    }


